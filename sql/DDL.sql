CREATE DATABASE IF NOT EXISTS muriel
    DEFAULT CHARACTER SET utf8mb4;

USE muriel;

CREATE TABLE `CLIENTE` (
    `ID_CLIENTE` INT NOT NULL AUTO_INCREMENT,
    `UF_CLIENTE` CHAR(2) NOT NULL,
    `CEP_CLIENTE` CHAR(8) NOT NULL,
    `TEL_CLIENTE` VARCHAR(20) NOT NULL,
    `NM_CLIENTE` VARCHAR(255) NOT NULL,
    `ENDERECO_CLIENTE` VARCHAR(255) NOT NULL,
    `CPF_CLIENTE` CHAR(11) NULL,
    PRIMARY KEY (`ID_CLIENTE`),
    CONSTRAINT `UQ_CLIENTE_CPF_CLIENTE` UNIQUE (`CPF_CLIENTE`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `PESSOA_FISICA` (
    `ID_CLIENTE` INT NOT NULL,
    PRIMARY KEY (`ID_CLIENTE`),
    CONSTRAINT `FK_PESSOA_FISICA_ID_CLIENTE` FOREIGN KEY (`ID_CLIENTE`)
        REFERENCES `CLIENTE` (`ID_CLIENTE`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `PESSOA_JURIDICA` (
    `ID_CLIENTE` INT NOT NULL,
    `CNPJ` CHAR(14) NOT NULL,
    PRIMARY KEY (`ID_CLIENTE`),
    CONSTRAINT `UQ_PESSOA_JURIDICA_CNPJ` UNIQUE (`CNPJ`),
    CONSTRAINT `FK_PESSOA_JURIDICA_ID_CLIENTE` FOREIGN KEY (`ID_CLIENTE`)
        REFERENCES `CLIENTE` (`ID_CLIENTE`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `FUNCIONARIO` (
    `ID_FUNCIONARIO` INT NOT NULL AUTO_INCREMENT,
    `TEL_FUNCIONARIO` VARCHAR(20) NULL,
    `NM_FUNCIONARIO` VARCHAR(255) NOT NULL,
    `DT_ADMISSAO` DATE NOT NULL,
    `EMAIL_FUNCIONARIO` VARCHAR(255) NULL,
    PRIMARY KEY (`ID_FUNCIONARIO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `FUNC_SAC` (
    `ID_FUNCIONARIO` INT NOT NULL,
    PRIMARY KEY (`ID_FUNCIONARIO`),
    CONSTRAINT `FK_FUNC_SAC_ID_FUNCIONARIO` FOREIGN KEY (`ID_FUNCIONARIO`)
        REFERENCES `FUNCIONARIO` (`ID_FUNCIONARIO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `FUNC_VENDAS` (
    `ID_FUNCIONARIO` INT NOT NULL,
    PRIMARY KEY (`ID_FUNCIONARIO`),
    CONSTRAINT `FK_FUNC_VENDAS_ID_FUNCIONARIO` FOREIGN KEY (`ID_FUNCIONARIO`)
        REFERENCES `FUNCIONARIO` (`ID_FUNCIONARIO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `FUNC_PRODUCAO` (
    `ID_FUNCIONARIO` INT NOT NULL,
    PRIMARY KEY (`ID_FUNCIONARIO`),
    CONSTRAINT `FK_FUNC_PRODUCAO_ID_FUNCIONARIO` FOREIGN KEY (`ID_FUNCIONARIO`)
        REFERENCES `FUNCIONARIO` (`ID_FUNCIONARIO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `REGISTRO_PONTO` (
    `ID_REGISTRO` INT NOT NULL AUTO_INCREMENT,
    `ID_FUNCIONARIO` INT NOT NULL,
    `DT_REGISTRO` DATE NOT NULL,
    `HR_REGISTRO` TIME NOT NULL,
    `TIPO_REGISTRO` VARCHAR(30) NOT NULL,
    PRIMARY KEY (`ID_REGISTRO`),
    CONSTRAINT `FK_REGISTRO_PONTO_ID_FUNCIONARIO` FOREIGN KEY (`ID_FUNCIONARIO`)
        REFERENCES `FUNCIONARIO` (`ID_FUNCIONARIO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `PRODUTO` (
    `ID_PRODUTO` INT NOT NULL AUTO_INCREMENT,
    `DESCRICAO_PRODUTO` VARCHAR(255) NULL,
    `UNIDADE_PRODUTO` INT NOT NULL,
    `NM_PRODUTO` VARCHAR(255) NOT NULL,
    `EAN_PRODUTO` CHAR(13) NOT NULL,
    PRIMARY KEY (`ID_PRODUTO`),
    CONSTRAINT `UQ_PRODUTO_EAN_PRODUTO` UNIQUE (`EAN_PRODUTO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `MATERIAL` (
    `ID_MATERIAL` INT NOT NULL AUTO_INCREMENT,
    `NM_MATERIAL` VARCHAR(255) NOT NULL,
    `ESTOQUE_MIN_MATERIAL` INT NOT NULL,
    `UNIDADE_MATERIAL` INT NOT NULL,
    PRIMARY KEY (`ID_MATERIAL`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `FORNECEDOR` (
    `ID_FORNECEDOR` INT NOT NULL AUTO_INCREMENT,
    `TEL_FORNECEDOR` VARCHAR(20) NOT NULL,
    `CNPJ_FORNECEDOR` CHAR(14) NOT NULL,
    `ENDERECO_FORNECEDOR` VARCHAR(200) NOT NULL,
    `NM_FORNECEDOR` VARCHAR(255) NOT NULL,
    `CEP_FORNECEDOR` CHAR(8) NOT NULL,
    PRIMARY KEY (`ID_FORNECEDOR`),
    CONSTRAINT `UQ_FORNECEDOR_CNPJ_FORNECEDOR` UNIQUE (`CNPJ_FORNECEDOR`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `EMBALAGEM` (
    `ID_EMBALAGEM` INT NOT NULL AUTO_INCREMENT,
    `CAPACIDADE_EMBALAGEM` INT NOT NULL,
    `MATERIAL_EMBALAGEM` VARCHAR(80) NOT NULL,
    `TIPO_EMBALAGEM` VARCHAR(80) NOT NULL,
    PRIMARY KEY (`ID_EMBALAGEM`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `ATENDIMENTO_SAC` (
    `ID_ATENDIMENTO` INT NOT NULL AUTO_INCREMENT,
    `ID_CLIENTE` INT NOT NULL,
    `ID_FUNCIONARIO` INT NOT NULL,
    `PROTOCOLO` VARCHAR(40) NOT NULL,
    `DT_ATENDIMENTO` DATE NOT NULL,
    `TIPO_ATENDIMENTO` VARCHAR(40) NOT NULL,
    `DESCRICAO_ATENDIMENTO` VARCHAR(500) NOT NULL,
    `STATUS_ATENDIMENTO` VARCHAR(30) NOT NULL,
    PRIMARY KEY (`ID_ATENDIMENTO`),
    CONSTRAINT `UQ_ATENDIMENTO_SAC_PROTOCOLO` UNIQUE (`PROTOCOLO`),
    CONSTRAINT `FK_ATENDIMENTO_SAC_ID_CLIENTE` FOREIGN KEY (`ID_CLIENTE`)
        REFERENCES `CLIENTE` (`ID_CLIENTE`),
    CONSTRAINT `FK_ATENDIMENTO_SAC_ID_FUNCIONARIO` FOREIGN KEY (`ID_FUNCIONARIO`)
        REFERENCES `FUNC_SAC` (`ID_FUNCIONARIO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `PEDIDO` (
    `ID_PEDIDO` INT NOT NULL AUTO_INCREMENT,
    `ID_CLIENTE` INT NOT NULL,
    `ID_FUNCIONARIO` INT NOT NULL,
    `DT_PEDIDO` DATE NOT NULL,
    `PRECO_PEDIDO` DECIMAL(12,2) NOT NULL,
    `STATUS_PEDIDO` VARCHAR(40) NOT NULL,
    PRIMARY KEY (`ID_PEDIDO`),
    CONSTRAINT `FK_PEDIDO_ID_CLIENTE` FOREIGN KEY (`ID_CLIENTE`)
        REFERENCES `CLIENTE` (`ID_CLIENTE`),
    CONSTRAINT `FK_PEDIDO_ID_FUNCIONARIO` FOREIGN KEY (`ID_FUNCIONARIO`)
        REFERENCES `FUNC_VENDAS` (`ID_FUNCIONARIO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `ITEM_PEDIDO` (
    `ID_PEDIDO` INT NOT NULL,
    `ID_PRODUTO` INT NOT NULL,
    `QUANTIDADE_PEDIDA` INT NOT NULL,
    PRIMARY KEY (`ID_PEDIDO`, `ID_PRODUTO`),
    CONSTRAINT `FK_ITEM_PEDIDO_ID_PEDIDO` FOREIGN KEY (`ID_PEDIDO`)
        REFERENCES `PEDIDO` (`ID_PEDIDO`),
    CONSTRAINT `FK_ITEM_PEDIDO_ID_PRODUTO` FOREIGN KEY (`ID_PRODUTO`)
        REFERENCES `PRODUTO` (`ID_PRODUTO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `PAGAMENTO` (
    `ID_PAGAMENTO` INT NOT NULL AUTO_INCREMENT,
    `ID_PEDIDO` INT NOT NULL,
    `VALOR_PAGAMENTO` DECIMAL(12,2) NOT NULL,
    `STATUS_PAGAMENTO` VARCHAR(40) NOT NULL,
    `FORMA_PAGAMENTO` VARCHAR(40) NOT NULL,
    `DT_PAGAMENTO` DATE NULL,
    PRIMARY KEY (`ID_PAGAMENTO`),
    CONSTRAINT `FK_PAGAMENTO_ID_PEDIDO` FOREIGN KEY (`ID_PEDIDO`)
        REFERENCES `PEDIDO` (`ID_PEDIDO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `NOTA_FISCAL` (
    `ID_NF` INT NOT NULL AUTO_INCREMENT,
    `ID_PEDIDO` INT NOT NULL,
    `NUM_NF` VARCHAR(20) NOT NULL,
    `SERIE_NF` VARCHAR(10) NOT NULL,
    `STATUS_NF` VARCHAR(40) NOT NULL,
    `CHAVE_ACESSO` CHAR(44) NOT NULL,
    `VALOR_TOTAL` DECIMAL(12,2) NOT NULL,
    `DT_EMISSAO` DATE NOT NULL,
    PRIMARY KEY (`ID_NF`),
    CONSTRAINT `UQ_NOTA_FISCAL_ID_PEDIDO` UNIQUE (`ID_PEDIDO`),
    CONSTRAINT `UQ_NOTA_FISCAL_CHAVE_ACESSO` UNIQUE (`CHAVE_ACESSO`),
    CONSTRAINT `FK_NOTA_FISCAL_ID_PEDIDO` FOREIGN KEY (`ID_PEDIDO`)
        REFERENCES `PEDIDO` (`ID_PEDIDO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `DEVOLUCAO` (
    `ID_DEVOLUCAO` INT NOT NULL AUTO_INCREMENT,
    `ID_NF` INT NOT NULL,
    `ID_PEDIDO` INT NOT NULL,
    `ID_ATENDIMENTO` INT NOT NULL,
    `ID_PRODUTO` INT NOT NULL,
    `DT_DEVOLUCAO` DATE NOT NULL,
    `MOTIVO` VARCHAR(255) NOT NULL,
    `STATUS_DEVOLUCAO` VARCHAR(40) NOT NULL,
    `REEMBOLSO_DEVOLUCAO` DECIMAL(12,2) NULL,
    `QUANTIDADE_DEVOLVIDA` INT NOT NULL,
    PRIMARY KEY (`ID_DEVOLUCAO`),
    CONSTRAINT `UQ_DEVOLUCAO_ID_ATENDIMENTO` UNIQUE (`ID_ATENDIMENTO`),
    CONSTRAINT `FK_DEVOLUCAO_ID_NF` FOREIGN KEY (`ID_NF`)
        REFERENCES `NOTA_FISCAL` (`ID_NF`),
    CONSTRAINT `FK_DEVOLUCAO_ID_PEDIDO` FOREIGN KEY (`ID_PEDIDO`)
        REFERENCES `PEDIDO` (`ID_PEDIDO`),
    CONSTRAINT `FK_DEVOLUCAO_ID_ATENDIMENTO` FOREIGN KEY (`ID_ATENDIMENTO`)
        REFERENCES `ATENDIMENTO_SAC` (`ID_ATENDIMENTO`),
    CONSTRAINT `FK_DEVOLUCAO_ID_PRODUTO` FOREIGN KEY (`ID_PRODUTO`)
        REFERENCES `PRODUTO` (`ID_PRODUTO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `ENTREGA` (
    `ID_ENTREGA` INT NOT NULL AUTO_INCREMENT,
    `ID_NF` INT NOT NULL,
    `DT_ENVIO` DATE NULL,
    `DT_ENTREGA` DATE NULL,
    `STATUS_ENTREGA` VARCHAR(40) NOT NULL,
    `COD_RASTREIO` VARCHAR(50) NULL,
    `NM_MOTORISTA` VARCHAR(255) NULL,
    `PLACA_CAMINHAO` VARCHAR(10) NULL,
    `TRANSPORTADORA` VARCHAR(255) NULL,
    PRIMARY KEY (`ID_ENTREGA`),
    CONSTRAINT `UQ_ENTREGA_ID_NF` UNIQUE (`ID_NF`),
    CONSTRAINT `FK_ENTREGA_ID_NF` FOREIGN KEY (`ID_NF`)
        REFERENCES `NOTA_FISCAL` (`ID_NF`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `FATURAMENTO` (
    `ID_FATURAMENTO` INT NOT NULL AUTO_INCREMENT,
    `ID_NF` INT NOT NULL,
    `DT_FATURAMENTO` DATE NOT NULL,
    `STATUS` VARCHAR(40) NOT NULL,
    `DT_VENCIMENTO` DATE NOT NULL,
    `VALOR_TOTAL` DECIMAL(12,2) NOT NULL,
    PRIMARY KEY (`ID_FATURAMENTO`),
    CONSTRAINT `UQ_FATURAMENTO_ID_NF` UNIQUE (`ID_NF`),
    CONSTRAINT `FK_FATURAMENTO_ID_NF` FOREIGN KEY (`ID_NF`)
        REFERENCES `NOTA_FISCAL` (`ID_NF`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `LOTE` (
    `ID_LOTE` INT NOT NULL AUTO_INCREMENT,
    `ID_PRODUTO` INT NOT NULL,
    `QUANTIDADE_LOTE` INT NOT NULL,
    `DT_FABRICACAO` DATE NOT NULL,
    `NUM_LOTE` VARCHAR(30) NOT NULL,
    `DT_VALIDADE` DATE NOT NULL,
    PRIMARY KEY (`ID_LOTE`),
    CONSTRAINT `FK_LOTE_ID_PRODUTO` FOREIGN KEY (`ID_PRODUTO`)
        REFERENCES `PRODUTO` (`ID_PRODUTO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `PEDIDO_MATERIAL` (
    `ID_PEDIDO_MATERIAL` INT NOT NULL AUTO_INCREMENT,
    `ID_FORNECEDOR` INT NOT NULL,
    `ID_MATERIAL` INT NOT NULL,
    `DT_PEDIDO` DATE NOT NULL,
    `QUANTIDADE_SOLICITADA` INT NOT NULL,
    `PRECO_UNITARIO` DECIMAL(12,2) NOT NULL,
    `DT_PREVISTA` DATE NULL,
    `PRECO_TOTAL` DECIMAL(12,2) NOT NULL,
    `STATUS` VARCHAR(40) NOT NULL,
    PRIMARY KEY (`ID_PEDIDO_MATERIAL`),
    CONSTRAINT `FK_PEDIDO_MATERIAL_ID_FORNECEDOR` FOREIGN KEY (`ID_FORNECEDOR`)
        REFERENCES `FORNECEDOR` (`ID_FORNECEDOR`),
    CONSTRAINT `FK_PEDIDO_MATERIAL_ID_MATERIAL` FOREIGN KEY (`ID_MATERIAL`)
        REFERENCES `MATERIAL` (`ID_MATERIAL`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `PRODUCAO` (
    `ID_PRODUCAO` INT NOT NULL AUTO_INCREMENT,
    `ID_PRODUTO` INT NOT NULL,
    `QUANTIDADE_PRODUCAO` INT NOT NULL,
    `STATUS_PRODUCAO` VARCHAR(40) NOT NULL,
    `DT_INICIO_PRODUCAO` DATE NOT NULL,
    PRIMARY KEY (`ID_PRODUCAO`),
    CONSTRAINT `FK_PRODUCAO_ID_PRODUTO` FOREIGN KEY (`ID_PRODUTO`)
        REFERENCES `PRODUTO` (`ID_PRODUTO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `PRODUTO_MATERIAL` (
    `ID_MATERIAL` INT NOT NULL,
    `ID_PRODUTO` INT NOT NULL,
    PRIMARY KEY (`ID_MATERIAL`, `ID_PRODUTO`),
    CONSTRAINT `FK_PRODUTO_MATERIAL_ID_MATERIAL` FOREIGN KEY (`ID_MATERIAL`)
        REFERENCES `MATERIAL` (`ID_MATERIAL`),
    CONSTRAINT `FK_PRODUTO_MATERIAL_ID_PRODUTO` FOREIGN KEY (`ID_PRODUTO`)
        REFERENCES `PRODUTO` (`ID_PRODUTO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `PRODUTO_EMBALAGEM` (
    `ID_PRODUTO` INT NOT NULL,
    `ID_EMBALAGEM` INT NOT NULL,
    PRIMARY KEY (`ID_PRODUTO`, `ID_EMBALAGEM`),
    CONSTRAINT `FK_PRODUTO_EMBALAGEM_ID_PRODUTO` FOREIGN KEY (`ID_PRODUTO`)
        REFERENCES `PRODUTO` (`ID_PRODUTO`),
    CONSTRAINT `FK_PRODUTO_EMBALAGEM_ID_EMBALAGEM` FOREIGN KEY (`ID_EMBALAGEM`)
        REFERENCES `EMBALAGEM` (`ID_EMBALAGEM`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE `FUNCIONARIO_PRODUCAO` (
    `ID_PRODUCAO` INT NOT NULL,
    `ID_FUNCIONARIO` INT NOT NULL,
    PRIMARY KEY (`ID_PRODUCAO`, `ID_FUNCIONARIO`),
    CONSTRAINT `FK_FUNCIONARIO_PRODUCAO_ID_PRODUCAO` FOREIGN KEY (`ID_PRODUCAO`)
        REFERENCES `PRODUCAO` (`ID_PRODUCAO`),
    CONSTRAINT `FK_FUNCIONARIO_PRODUCAO_ID_FUNCIONARIO` FOREIGN KEY (`ID_FUNCIONARIO`)
        REFERENCES `FUNC_PRODUCAO` (`ID_FUNCIONARIO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4;
